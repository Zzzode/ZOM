template <typename Fn>
void visitTreePreOrder(const Tree& tree, NodeId node, Fn&& fn) {
  fn(node, tree.node(node));
  visitChildNodeIds(tree, tree.node(node), [&](NodeId child) {
    visitTreePreOrder(tree, child, fn);
  });
}

